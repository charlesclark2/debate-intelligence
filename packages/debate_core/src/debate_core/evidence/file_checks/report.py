CHECKER_VERSION: Final = "2026.10.19-file-checks-1"
"""Version of these checks, recorded in every report. Bumped whenever a check's verdict can change."""

FILE_QUALITY_SCHEMA_FILENAME: Final = "file-quality-report.schema.json"
"""The published schema's file name, under `docs/data/`."""

QUALITY_JSON_SUFFIX: Final = ".quality.json"
QUALITY_MARKDOWN_SUFFIX: Final = ".quality.md"


def quality_report_names(docx_name: str) -> tuple[str, str]:
    """The two reports' file names for a built file's name: `<file>.quality.json`, `<file>.quality.md`.

    Named as the provenance sidecar is (`nhi-politics.docx.provenance.json`), so the three sit together.
    """
    return f"{docx_name}{QUALITY_JSON_SUFFIX}", f"{docx_name}{QUALITY_MARKDOWN_SUFFIX}"


class CheckStatus(StrEnum):
    PASS = "PASS"
    WARN = "WARN"
    FAIL = "FAIL"


_SEVERITY: Final = {CheckStatus.PASS: 0, CheckStatus.WARN: 1, CheckStatus.FAIL: 2}


def _worst(statuses: Iterable[CheckStatus]) -> CheckStatus:
    return max(statuses, key=_SEVERITY.__getitem__, default=CheckStatus.PASS)


class QualityCheck(StrEnum):
    """The checks, each by the name a report gives it."""

    SIDECAR = "sidecar"
    EVIDENCE_IDENTITY = "evidence-identity"
    CITE_PRESENT = "cite-present"
    DUPLICATE_CARDS = "duplicate-cards"
    HEADING_STRUCTURE = "heading-structure"
    MANIFEST_ALIGNMENT = "manifest-alignment"
    PROVENANCE_COMPLETE = "provenance-complete"
    SUPPRESSION = "suppression"


CHECK_DESCRIPTIONS: Final[dict[QualityCheck, str]] = {
    QualityCheck.SIDECAR: "The provenance sidecar is readable, valid and describes these bytes.",
    QualityCheck.EVIDENCE_IDENTITY: (
        "Each card's evidence text, cite, formatting and fingerprint are its source card's, re-parsed "
        "from both files."
    ),
    QualityCheck.CITE_PRESENT: "Each card has a cite with a short cite (warned, never failed).",
    QualityCheck.DUPLICATE_CARDS: "No fingerprint appears twice; near-duplicate cards are warnings.",
    QualityCheck.HEADING_STRUCTURE: (
        "Headings nest pocket > hat > block > tag, no level skipped, in profile styles."
    ),
    QualityCheck.MANIFEST_ALIGNMENT: "The sidecar and the document agree card for card, in order.",
    QualityCheck.PROVENANCE_COMPLETE: (
        "Each card's provenance is complete, and its provenance line is below its cite, in Undertag."
    ),
    QualityCheck.SUPPRESSION: "No card comes from a source or disclosure on the suppression list.",
}


class CheckResult(DomainModel):
    """One finding of one check: about one card, one place in the document, or the whole file."""

    check: QualityCheck = Field(description="Which check this is.")
    status: CheckStatus = Field(description="PASS, WARN or FAIL.")
    card_position: int | None = Field(
        default=None, ge=1, description="The card's place in the built file, from 1; None for the file."
    )
    fingerprint: Sha256Hex | None = Field(default=None, description="The card's exact fingerprint, if known.")
    section_path: tuple[NonEmptyText, ...] | None = Field(
        default=None, description="The headings above the place this is about, outermost first."
    )
    paragraph_index: int | None = Field(
        default=None, ge=0, description="The paragraph of the built file this is about, from 0."
    )
    message: NonEmptyText = Field(description="What was found. Names fields and digests, never card text.")


class CheckSummary(DomainModel):
    """One check over the whole file: its worst result and how many results failed or warned."""

    check: QualityCheck = Field(description="Which check this is.")
    description: NonEmptyText = Field(description="What the check asks.")
    status: CheckStatus = Field(description="The worst status among its results.")
    failures: int = Field(ge=0, description="Results that FAIL.")
    warnings: int = Field(ge=0, description="Results that WARN.")


class FileQualityReport(DomainModel):
    """`<file>.quality.json`: every check's results for one built file, and the versions behind them."""

    schema_version: Literal[1] = Field(default=1, description="The report's shape: 1.")
    status: Literal[CheckStatus.PASS, CheckStatus.FAIL] = Field(
        description="FAIL when any result fails; PASS otherwise, warnings or not."
    )
    checker_version: NonEmptyText = Field(description="Version of the checks.")
    parser_version: NonEmptyText = Field(description="Version of the parser that re-read the files.")
    style_profile_version: NonEmptyText = Field(description="Version of the style profile it read them with.")
    fingerprint_version: NonEmptyText = Field(description="Version of the fingerprints it recomputed.")
    builder_version: NonEmptyText | None = Field(
        default=None, description="The writer's version, as the sidecar records it; None without one."
    )
    sidecar_parser_version: NonEmptyText | None = Field(
        default=None, description="The parser version the sidecar records; None without one."
    )
    docx_sha256: Sha256Hex = Field(description="SHA-256 of the built file's bytes as checked.")
    recipe_hash: Sha256Hex | None = Field(default=None, description="The recipe's hash, from the sidecar.")
    card_count: int = Field(ge=0, description="Cards the built file reads as.")
    manifest_card_count: int | None = Field(
        default=None, ge=0, description="Entries in the sidecar; None when it could not be read."
    )
    checks: tuple[CheckSummary, ...] = Field(description="One summary per check, in a fixed order.")
    results: tuple[CheckResult, ...] = Field(description="Every result, check by check.")

    @model_validator(mode="after")
    def _check_report(self) -> Self:
        if [summary.check for summary in self.checks] != list(QualityCheck):
            raise ValueError("a report summarises every check once, in order")
        for summary in self.checks:
            mine = [result.status for result in self.results if result.check is summary.check]
            if (
                summary.status is not _worst(mine)
                or summary.failures != mine.count(CheckStatus.FAIL)
                or summary.warnings != mine.count(CheckStatus.WARN)
            ):
                raise ValueError(f"the summary of {summary.check} does not count its results")
        failed = any(result.status is CheckStatus.FAIL for result in self.results)
        if self.status is not (CheckStatus.FAIL if failed else CheckStatus.PASS):
            raise ValueError("a report fails exactly when one of its results fails")
        return self

    @classmethod
    def from_results(cls, results: Sequence[CheckResult], **fields: Any) -> FileQualityReport:
        """A report of `results`, ordered check by check, with its summaries and status worked out."""
        order = {check: index for index, check in enumerate(QualityCheck)}
        ordered = tuple(sorted(results, key=lambda result: order[result.check]))
        summaries: list[CheckSummary] = []
        for check in QualityCheck:
            mine = [result.status for result in ordered if result.check is check]
            summaries.append(
                CheckSummary(
                    check=check,
                    description=CHECK_DESCRIPTIONS[check],
                    status=_worst(mine),
                    failures=mine.count(CheckStatus.FAIL),
                    warnings=mine.count(CheckStatus.WARN),
                )
            )
        failed = any(result.status is CheckStatus.FAIL for result in ordered)
        return cls(
            status=CheckStatus.FAIL if failed else CheckStatus.PASS,
            checks=tuple(summaries),
            results=ordered,
            **fields,
        )

    def summary(self, check: QualityCheck) -> CheckSummary:
        return next(summary for summary in self.checks if summary.check is check)

    def failed(self, check: QualityCheck) -> bool:
        """Whether `check` has a failing result."""
        return self.summary(check).status is CheckStatus.FAIL

    def to_json_bytes(self) -> bytes:
        """The report's bytes: two-space indented JSON, keys in model order, UTF-8, a final newline."""
        return (json.dumps(self.model_dump(mode="json"), indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _short(fingerprint: str | None) -> str:
    return f"`{fingerprint[:12]}`" if fingerprint else "-"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown(report: FileQualityReport) -> str:
    """`<file>.quality.md`: the same report for a person. Cards by position and fingerprint prefix."""
    lines = [
        "# Built-file quality report",
        "",
        "| | |",
        "|---|---|",
        f"| Overall | **{report.status}** |",
        f"| Built file (SHA-256) | `{report.docx_sha256[:16]}` |",
        f"| Cards in the file / in the sidecar | {report.card_count} / "
        f"{'-' if report.manifest_card_count is None else report.manifest_card_count} |",
        f"| Checker | `{report.checker_version}` |",
        f"| Parser | `{report.parser_version}` |",
        f"| Style profile | `{report.style_profile_version}` |",
        f"| Fingerprints | `{report.fingerprint_version}` |",
        f"| Writer (from the sidecar) | `{report.builder_version or '-'}` |",
        "",
        "## Checks",
        "",
        "| Check | Status | Failures | Warnings | What it asks |",
        "|---|---|---|---|---|",
    ]
    lines.extend(
        f"| `{summary.check}` | {summary.status} | {summary.failures} | {summary.warnings} | "
        f"{_cell(summary.description)} |"
        for summary in report.checks
    )

    per_card = [
        check
        for check in QualityCheck
        if any(result.check is check and result.card_position is not None for result in report.results)
    ]
    positions = sorted(
        {result.card_position for result in report.results if result.card_position is not None}
    )
    if positions:
        lines += [
            "",
            "## Cards",
            "",
            "| Card | Fingerprint | " + " | ".join(f"`{c}`" for c in per_card) + " |",
        ]
        lines.append("|---|---|" + "---|" * len(per_card))
        for position in positions:
            mine = [result for result in report.results if result.card_position == position]
            fingerprint = next((result.fingerprint for result in mine if result.fingerprint), None)
            cells: list[str] = []
            for check in per_card:
                statuses = [result.status for result in mine if result.check is check]
                cells.append(str(_worst(statuses)) if statuses else "-")
            lines.append(f"| {position} | {_short(fingerprint)} | " + " | ".join(cells) + " |")

    findings = [result for result in report.results if result.status is not CheckStatus.PASS]
    lines += ["", "## Failures and warnings", ""]
    if not findings:
        lines.append("None.")
    for result in findings:
        where: list[str] = []
        if result.card_position is not None:
            where.append(f"card {result.card_position} ({_short(result.fingerprint)})")
        if result.paragraph_index is not None:
            where.append(f"paragraph {result.paragraph_index}")
        if result.section_path:
            where.append("under " + " > ".join(result.section_path))
        place = f" {', '.join(where)}:" if where else ""
        lines.append(f"* **{result.status}** `{result.check}`{place} {_cell(result.message)}")
    return "\n".join(lines) + "\n"


def render_file_quality_report_schema() -> dict[str, Any]:
    """The report's JSON Schema, for `docs/data/file-quality-report.schema.json`."""
    return {"$schema": JSON_SCHEMA_DIALECT, **FileQualityReport.model_json_schema(mode="serialization")}
