def bot_branch(tmp_path: Path, *commits: dict[str, str | None], dev_moves_on: bool = False) -> Path:
    """A checkout of the bot's branch as ci.yml's selection job has it for a dispatched run: a clone,
    all history and origin/dev, HEAD detached at the branch. The branch is `commits` on dev's tip,
    and dev may have moved on since, as it does before the bot catches up."""
    source = tmp_path / "source"
    source.mkdir()
    git(source, "init", "-q", "-b", "dev")
    git(source, "config", "user.email", "ci@example.invalid")
    git(source, "config", "user.name", "CI")
    write(source, dict(BASE))
    git(source, "add", "-A")
    git(source, "commit", "-q", "-m", "base")
    git(source, "switch", "-q", "-c", GENERATED_FILES_BRANCH)
    for number, files in enumerate(commits):
        write(source, files)
        git(source, "add", "-A")
        git(source, "commit", "-q", "-m", f"commit {number}")
    git(source, "switch", "-q", "dev")
    if dev_moves_on:
        write(source, A_DOMAIN_CHANGE)
        git(source, "commit", "-q", "-am", "a later merge into dev")
    checkout = tmp_path / "checkout"
    git(tmp_path, "clone", "-q", f"file://{source}", str(checkout))
    git(checkout, "switch", "-q", "--detach", f"origin/{GENERATED_FILES_BRANCH}")
    return checkout


def dispatched(root: Path, tmp_path: Path, ref_name: str = GENERATED_FILES_BRANCH) -> Ran:
    """refresh-generated-files.yml's `gh workflow run ci.yml --ref <branch>`: no base branch or commit."""
    return run(root, tmp_path, event="workflow_dispatch", base_branch="", base_sha="", ref_name=ref_name)


@pytest.mark.parametrize("dev_moves_on", [False, True], ids=["on-dev-tip", "dev-moved-on"])
def test_the_bots_dispatched_run_on_its_branch_runs_no_test_part(tmp_path: Path, dev_moves_on: bool) -> None:
    """A pull request opened with the workflow token starts no pull_request run, so the bot
    dispatches ci on its branch; its one commit on dev changes only the generated files."""
    root = bot_branch(tmp_path, REGENERATED, dev_moves_on=dev_moves_on)

    ran = dispatched(root, tmp_path)

    assert_none(ran, f"because {GENERATED_FILES_BRANCH} changes only the generated files")


def test_a_dispatched_run_of_the_bots_branch_carrying_more_runs_the_whole_selection(tmp_path: Path) -> None:
    """Someone else's commit under the bot's: the branch carries code, whatever its last commit does."""
    root = bot_branch(tmp_path, A_DOMAIN_CHANGE, REGENERATED)

