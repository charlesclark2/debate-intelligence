BUILT_FILE_METADATA_SCHEMA_VERSION: Final = 1
"""The metadata's shape. Bumped by a change an existing reader would break on."""

BUILT_FILE_METADATA_SCHEMA_FILENAME: Final = "built-file-metadata.schema.json"
"""The published schema's file name, under `docs/data/`."""

FILES_PREFIX: Final = "files/"
"""The evidence bucket's prefix for built files (`docs/architecture/evidence-store-layout.md`)."""

METADATA_NAME: Final = "metadata.json"
RECIPE_NAME: Final = "recipe.yaml"

RECIPE_HASH_KEY_LENGTH: Final = 12
"""How much of the recipe hash names a published version: 48 bits, so two recipes of one slug never meet."""

SLUG_PATTERN: Final = r"^[a-z0-9]+(?:-[a-z0-9]+)*$"
"""A built file's slug: kebab-case, as recipes are named (`policy-nhi-politics-da-answers`)."""

_SLUG = re.compile(SLUG_PATTERN)
_RECIPE_ID = re.compile(RECIPE_ID_PATTERN)
_SHA256 = re.compile(r"^[0-9a-f]{64}$")

#: The sides a built file is for. `UNKNOWN` describes an unreadable disclosure, never a file.
_FILE_SIDES: Final = frozenset({Side.AFF, Side.NEG, Side.PRO, Side.CON})

Slug = Annotated[str, StringConstraints(pattern=SLUG_PATTERN, max_length=100)]
RecipeId = Annotated[str, StringConstraints(pattern=RECIPE_ID_PATTERN, max_length=64)]
StoreName = Annotated[str, StringConstraints(pattern=RECIPE_STORE_PATTERN)]


def built_file_prefix(*, topic: str, side: Side, position: str, slug: str, recipe_hash: str) -> str:
    """`files/<topic>/<side>/<position>/<slug>/<recipe hash, 12>/`, the side in lower case.

    Raises :class:`ValueError` for a part that would not make a key: a topic or position that is not
    a recipe id, a slug that is not kebab-case, a side no file is for, or a recipe hash that is not a
    SHA-256.
    """
    if _RECIPE_ID.match(topic) is None or _RECIPE_ID.match(position) is None:
        raise ValueError("a topic and a position are kebab-case recipe ids")
    if _SLUG.match(slug) is None or len(slug) > 100:
        raise ValueError(f"a built file's slug is kebab-case, at most 100 characters: {slug!r}")
    if side not in _FILE_SIDES:
        raise ValueError(f"a built file is for AFF, NEG, PRO or CON, not {side}")
    if _SHA256.match(recipe_hash) is None:
        raise ValueError("a recipe hash is 64 lowercase hex characters")
    version = recipe_hash[:RECIPE_HASH_KEY_LENGTH]
    return f"{FILES_PREFIX}{topic}/{side.value.lower()}/{position}/{slug}/{version}/"


@dataclass(frozen=True, slots=True)
class BuiltFileKeys:
    """The five keys of one published file, in the order a publish writes them: metadata last."""

    prefix: str
    docx: str
    provenance: str
    quality: str
    recipe: str
    metadata: str

    @property
    def in_order(self) -> tuple[str, str, str, str, str]:
        return (self.docx, self.provenance, self.quality, self.recipe, self.metadata)


def built_file_keys(prefix: str, slug: str) -> BuiltFileKeys:
    """The keys under `prefix` (:func:`built_file_prefix`) of the file `<slug>.docx`."""
    docx = f"{slug}.docx"
    return BuiltFileKeys(
        prefix=prefix,
        docx=f"{prefix}{docx}",
        provenance=f"{prefix}{provenance_sidecar_name(docx)}",
        quality=f"{prefix}{docx}.quality.json",
        recipe=f"{prefix}{RECIPE_NAME}",
        metadata=f"{prefix}{METADATA_NAME}",
    )


class PublishedSource(DomainModel):
    """One source a published file has cards from, as its sidecar names it."""

    caselist: StoreName = Field(description="Caselist slug, or `openev` for a camp file.")
    snapshot: NonEmptyText = Field(
        description="The first snapshot listing the occurrence, as the sidecar records it; a camp release."
    )
    source_sha256: Sha256Hex = Field(description="SHA-256 of the source file, as the sidecar records it.")


def published_sources(cards: Iterable[FileProvenanceEntry]) -> tuple[PublishedSource, ...]:
    """Every source the sidecar's cards name, once per caselist, snapshot and SHA-256, sorted."""
    found = {(card.caselist, card.snapshot, card.source_sha256) for card in cards}
    return tuple(
        PublishedSource(caselist=caselist, snapshot=snapshot, source_sha256=sha)
        for caselist, snapshot, sha in sorted(found)
    )


class PublishedObject(DomainModel):
    """One object published beside the metadata: its name under the prefix, size and SHA-256."""

    name: NonEmptyText = Field(description="The object's name under the file's prefix.")
    bytes: int = Field(ge=0, description="Its size.")
    sha256: Sha256Hex = Field(description="SHA-256 of its bytes, as uploaded.")


class BuiltFileMetadata(DomainModel):
    """`metadata.json`: what a published built file is, how it was checked, and every source it cites."""

    schema_version: Literal[1] = Field(default=1, description="The metadata's shape: 1.")
    key_prefix: NonEmptyText = Field(
        description="The prefix of the file's objects: files/<topic>/<side>/<position>/<slug>/<hash12>/."
    )
    slug: Slug = Field(description="The built file's name without `.docx`.")
    title: NonEmptyText = Field(description="The recipe's title.")
    topic: RecipeId = Field(description="The recipe's topic id.")
    format: Event = Field(description="The event: POLICY, LD or PF.")
    caselist: StoreName = Field(description="The recipe's own caselist, which unpinned cards came from.")
    position: RecipeId = Field(description="The recipe's position id.")
    side: Side = Field(description="The side the file is for.")
    card_count: int = Field(ge=0, description="Cards in the file, as its sidecar lists them.")
    recipe_hash: Sha256Hex = Field(
        description="The recipe's canonical hash (v1-e33-t01), as the sidecar records it."
    )
    recipe_status: Literal[RecipeStatus.READY] = Field(
        description="Always ready: a file built from a draft recipe is never published."
    )
    builder_version: NonEmptyText = Field(description="Version of the writer that built the file.")
    parser_version: NonEmptyText = Field(
        description="Version of the parser the quality checks re-read it with."
    )
    style_profile_version: NonEmptyText = Field(
        description="Version of the style profile it was checked against."
    )
    fingerprint_version: NonEmptyText = Field(
        description="Version of the fingerprints the checks recomputed."
    )
    checker_version: NonEmptyText = Field(description="Version of the quality checks.")
    quality_status: Literal["PASS"] = Field(description="Always PASS: nothing else is published.")
    quality_warnings: int = Field(ge=0, description="How many check results warned. A warning never blocks.")
    warned_checks: tuple[NonEmptyText, ...] = Field(
        default=(), description="The checks with at least one warning, in the report's order."
    )
    built_at: AwareDatetime = Field(description="When the file was built, from its sidecar; UTC.")
    docx_sha256: Sha256Hex = Field(description="SHA-256 of the published `.docx`.")
    objects: tuple[PublishedObject, ...] = Field(
        description="The four objects published before this one: .docx, sidecar, quality report, recipe."
    )
    sources: tuple[PublishedSource, ...] = Field(
        description="Every source the sidecar names, once per caselist, snapshot and SHA-256, sorted."
    )
    caselists: tuple[StoreName, ...] = Field(description="The caselists of `sources`, sorted, once each.")
    source_sha256s: tuple[Sha256Hex, ...] = Field(description="The SHA-256s of `sources`, sorted, once each.")
    provenance_mode: Literal[ProvenanceMode.FILE_IMPORT] = Field(
        default=ProvenanceMode.FILE_IMPORT, description="Always FILE_IMPORT: no card is platform-verified."
    )

    @field_serializer("built_at")
    def _write_built_at(self, built_at: datetime) -> str:
        """Written in UTC with a `Z`, as the sidecar writes it."""
        return built_at.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%S.%fZ")

    @model_validator(mode="after")
    def _check_metadata(self) -> Self:
        expected = built_file_prefix(
            topic=self.topic,
            side=self.side,
            position=self.position,
            slug=self.slug,
            recipe_hash=self.recipe_hash,
        )
        if self.key_prefix != expected:
            raise ValueError("key_prefix is the one the topic, side, position, slug and recipe hash make")
        keys = built_file_keys(expected, self.slug)
        names = [key.removeprefix(expected) for key in keys.in_order[:-1]]
        if [one.name for one in self.objects] != names:
            raise ValueError(f"objects are {', '.join(names)}, in that order")
        if self.objects[0].sha256 != self.docx_sha256:
            raise ValueError("the .docx object is the file docx_sha256 names")
        if list(self.sources) != sorted(
            set(self.sources), key=lambda one: (one.caselist, one.snapshot, one.source_sha256)
        ):
            raise ValueError("sources are sorted by caselist, snapshot and SHA-256, once each")
        if self.caselists != tuple(sorted({one.caselist for one in self.sources})):
            raise ValueError("caselists are the sources' caselists, sorted, once each")
        if self.source_sha256s != tuple(sorted({one.source_sha256 for one in self.sources})):
            raise ValueError("source_sha256s are the sources' SHA-256s, sorted, once each")
        return self

    def to_json_bytes(self) -> bytes:
        """The object's bytes: two-space indented JSON, keys in model order, UTF-8, a final newline."""
        document = self.model_dump(mode="json")
        return (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def render_built_file_metadata_schema() -> dict[str, Any]:
    """The metadata's JSON Schema, for `docs/data/built-file-metadata.schema.json`."""
    return {"$schema": JSON_SCHEMA_DIALECT, **BuiltFileMetadata.model_json_schema(mode="serialization")}
