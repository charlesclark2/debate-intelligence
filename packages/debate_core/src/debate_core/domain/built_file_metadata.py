"""A published built file's `metadata.json`, and where in a bucket's `files/` prefix it lands (`v1-e33-t05`).

`debate-research files publish` puts each built evidence file that passed its quality checks under
one prefix of the evidence bucket, :func:`built_file_prefix`:

::

    files/<topic>/<side>/<position>/<slug>/<recipe hash, 12>/
        <slug>.docx                     the built file
        <slug>.docx.provenance.json     its provenance sidecar (v1-e33-t02)
        <slug>.docx.quality.json        the quality report for these exact bytes (v1-e33-t04)
        recipe.yaml                     the recipe, no pin naming a side, tournament, round, school or team
        metadata.json                   a BuiltFileMetadata, written last

`docs/data/built-file-metadata.md` describes the layout and the contract for the V2 debate tub
(`v2-e35-t02`) and the takedown flows (`v1-e30-t07`, `v2-e35-t05`), and
`docs/data/built-file-metadata.schema.json` is :func:`render_built_file_metadata_schema`, generated by
`scripts/export_built_file_metadata_schema.py` and held to the model by a drift test.

## Deterministic keys, deterministic bytes

The prefix is made from the recipe's topic, side and position, the built file's slug (its name
without `.docx`, which `files build` takes from the recipe's file name) and the first twelve
characters of the recipe hash. Nothing in it is a time, a person or a school. `metadata.json` holds
nothing that changes between two publishes of the same file: `built_at` is the sidecar's, and no
publish time is recorded. So publishing an unchanged file again writes nothing.

## Finding a file by its sources

A removal request names a source by its SHA-256 (data-use policy, Removal). `sources` lists every
source the file's sidecar names, once per caselist, snapshot and SHA-256, and `source_sha256s` and
`caselists` flatten them, so a takedown finds every published file built from a source by reading
`metadata.json` objects alone. The model refuses flattened arrays that are not exactly what
`sources` gives.

## Personal data

None. The school and team code a sidecar records are not copied here: the data-use policy names the
provenance sidecar as a place they may live, and not this file (the PM's question in this task's
session report). Titles, topics and positions are the coach's; slugs and caselist slugs name no team.
"""

