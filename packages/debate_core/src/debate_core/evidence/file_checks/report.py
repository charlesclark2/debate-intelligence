"""What the quality checks found: `<file>.quality.json`, `<file>.quality.md` and their schema.

Every check yields :class:`CheckResult` values, one per card it looked at (or one for the file), each
`PASS`, `WARN` or `FAIL`. :class:`FileQualityReport` gathers them with the versions that produced them
and an overall status: `FAIL` when any result fails, `PASS` otherwise. A warning never fails a file,
and nothing turns a failure into a warning: the checks decide a result's status, and this module only
counts them.

## No card text, school or team code

A report sits beside the built file and may be passed around more freely than the file itself. It
names a card by its position in the file and its fingerprint, a check by its name, and a heading by
the coach's own heading text (the recipe's, which the sidecar records); a message says *which field*
differs and never what it says. The Markdown names a card by position and fingerprint prefix.

## The schema

`docs/data/file-quality-report.schema.json` is :func:`render_file_quality_report_schema`, generated by
`scripts/export_file_quality_schema.py` and held to the model by a drift test.
"""

